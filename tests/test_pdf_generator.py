"""Tests for pdf_generator module."""

from pathlib import Path

import fitz  # type: ignore[import-untyped]  # PyMuPDF
import pytest

from openscientist.pdf_generator import ReportPDF, markdown_to_pdf


def _extract_text(pdf_path: Path) -> str:
    """Extract all rendered text from a PDF."""
    with fitz.open(pdf_path) as doc:
        return "\n".join(page.get_text() for page in doc)


def _horizontal_lines(pdf_path: Path) -> int:
    """Count full-width horizontal line strokes drawn on the pages."""
    count = 0
    with fitz.open(pdf_path) as doc:
        for page in doc:
            for drawing in page.get_drawings():
                for item in drawing["items"]:
                    if item[0] != "l":
                        continue
                    start, end = item[1], item[2]
                    if abs(start.y - end.y) < 0.5 and abs(end.x - start.x) > 100:
                        count += 1
    return count


class TestProcessInlineFormatting:
    """Tests for inline markdown processing."""

    def test_removes_backtick_code(self):
        result = ReportPDF._process_inline_formatting("Use `pandas` for data")
        assert "`" not in result
        assert "pandas" in result

    def test_preserves_bold(self):
        result = ReportPDF._process_inline_formatting("This is **bold** text")
        assert "**bold**" in result

    def test_preserves_italic(self):
        result = ReportPDF._process_inline_formatting("This is *italic* text")
        assert "*italic*" in result

    def test_plain_text_unchanged(self):
        text = "No formatting here"
        assert ReportPDF._process_inline_formatting(text) == text


class TestMarkdownToPdf:
    """Tests for full markdown-to-PDF conversion."""

    @pytest.fixture
    def sample_md(self, tmp_path: Path) -> Path:
        md = tmp_path / "report.md"
        md.write_text(
            "# Test Report\n\n"
            "## Introduction\n\n"
            "This is a test paragraph.\n\n"
            "### Details\n\n"
            "- Item one\n"
            "- Item two\n\n"
            "1. First\n"
            "2. Second\n\n"
            "```python\nprint('hello')\n```\n\n"
            "---\n\n"
            "#### Subheading\n\n"
            "Final paragraph with **bold** and `code`.\n"
        )
        return md

    def test_file_not_found_raises(self, tmp_path):
        with pytest.raises(FileNotFoundError):
            markdown_to_pdf(tmp_path / "nonexistent.md")

    def test_calls_correct_methods(self, sample_md, tmp_path):
        """Each markdown element type (title, headings, lists, code, paragraph, footer)
        is rendered into the produced PDF by the matching ReportPDF method."""
        pdf_path = tmp_path / "out.pdf"
        markdown_to_pdf(sample_md, pdf_path=pdf_path)

        content = pdf_path.read_bytes()
        assert content.startswith(b"%PDF")
        text = _extract_text(pdf_path)
        # "# Test Report"
        assert "Test Report" in text
        # "## Introduction"
        assert "Introduction" in text
        # "### Details"
        assert "Details" in text
        # "#### Subheading"
        assert "Subheading" in text
        # 2 unordered + 2 ordered list items
        assert "Item one" in text
        assert "Item two" in text
        assert "First" in text
        assert "Second" in text
        # code block
        assert "print('hello')" in text
        # paragraph
        assert "This is a test paragraph." in text
        # footer
        assert "Generated by OpenScientist" in text

    def test_no_footer_option(self, sample_md, tmp_path):
        """With add_footer=False the attribution footer is absent from the PDF."""
        pdf_path = tmp_path / "out.pdf"
        markdown_to_pdf(sample_md, pdf_path=pdf_path, add_footer=False)

        text = _extract_text(pdf_path)
        assert "Generated by OpenScientist" not in text
        # The rest of the document still rendered
        assert "Test Report" in text

    def test_default_pdf_path(self, sample_md):
        """Without an explicit path the PDF is written next to the markdown file."""
        result = markdown_to_pdf(sample_md)
        assert result == sample_md.with_suffix(".pdf")
        assert result.exists()

    def test_custom_pdf_path(self, sample_md, tmp_path):
        custom = tmp_path / "custom_name.pdf"
        result = markdown_to_pdf(sample_md, pdf_path=custom)
        assert result == custom
        assert custom.exists()

    def test_horizontal_rule_parsed(self, tmp_path):
        """A '---' line draws a horizontal rule between the surrounding paragraphs."""
        md = tmp_path / "hr.md"
        md.write_text("Text above\n\n---\n\nText below\n")
        pdf_path = tmp_path / "out.pdf"
        markdown_to_pdf(md, pdf_path=pdf_path, add_footer=False)

        text = _extract_text(pdf_path)
        assert "Text above" in text
        assert "Text below" in text
        # exactly one full-width horizontal line stroke, from the hr (footer off)
        assert _horizontal_lines(pdf_path) == 1
